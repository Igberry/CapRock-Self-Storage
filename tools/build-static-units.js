/* Write the current catalogue into the pages as real HTML.

   WHY THIS EXISTS
   The unit rows and the size guide cards are built by JavaScript from
   the live feed. Googlebot runs JavaScript and sees them. The crawlers
   behind the answer engines mostly do not: GPTBot, ClaudeBot,
   PerplexityBot and Common Crawl read the HTML as it is served. To
   them the location page said "Checking current availability..." and
   nothing else. No price, no size, nothing to quote. "How much is a
   10x10 in Lubbock" is the highest intent question there is, and the
   site could not answer it for the one audience that was asking.

   So each page now ships a snapshot: a plain table of every size and
   rate, in the markup, visible. When the live fetch lands it replaces
   the snapshot, so a visitor always sees live data and never the
   snapshot's date. Only a reader that cannot run scripts sees the
   table, which is exactly who it is for.

   This is not cloaking. It is the same content in the same place; one
   copy is current to the minute and the other is current to the day it
   was generated, and the table says which day.

   RUN IT when rates change:
     node tools/build-static-units.js
   Then rebuild the previews and repaste the two pages into GHL.

   It rewrites only what is between the BEGIN and END markers, so
   nothing else in either page can be disturbed. */
'use strict';

const fs = require('fs');
const path = require('path');

const ENDPOINT = 'https://cap-rock-self-storage.vercel.app/api/wss';
const FACILITY = 'lubbock-2213-n-quaker';
const ROOT = path.join(__dirname, '..');

const BEGIN = '<!-- BEGIN STATIC UNITS: generated by tools/build-static-units.js, do not hand edit -->';
const END = '<!-- END STATIC UNITS -->';

const esc = (v) => String(v == null ? '' : v)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const money = (v) => {
  const n = Number(v);
  if (!isFinite(n)) return '';
  return '$' + (n % 1 === 0 ? n.toFixed(0) : n.toFixed(2));
};

/* "30 September 2026". Spelled out, because a crawler reading 09/10
   cannot tell September from October and neither can half the world. */
function longDate(d) {
  const months = ['January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December'];
  return d.getDate() + ' ' + months[d.getMonth()] + ' ' + d.getFullYear();
}

function dims(u) {
  return [u.width, u.length].map(Number).join(' × ') +
    (u.height ? ' × ' + Number(u.height) : '');
}

async function get(resource) {
  const url = ENDPOINT + '?facility=' + encodeURIComponent(FACILITY) +
    '&resource=' + encodeURIComponent(resource);
  const r = await fetch(url);
  if (!r.ok) throw new Error(resource + ' returned ' + r.status);
  return r.json();
}

function table(units, when) {
  const rows = units.map((u) => {
    const type = u.climate ? 'Temperature controlled' : 'Drive-up';
    return '            <tr>' +
      '<th scope="row">' + esc(dims(u)) + ' ft</th>' +
      '<td>' + esc(u.sqft || '') + ' sq ft</td>' +
      '<td>' + esc(type) + '</td>' +
      '<td>' + esc(money(u.rate)) + ' per month</td>' +
      '</tr>';
  }).join('\n');

  return BEGIN + '\n' +
    '          <table class="crss-unit-static">\n' +
    '            <caption>Unit sizes and monthly rates at CapRock Self Storage, 2213 North Quaker Avenue, Lubbock, Texas. ' +
    'Rates confirmed ' + esc(when) + '. Live availability replaces this table when it loads.</caption>\n' +
    '            <thead>\n' +
    '              <tr><th scope="col">Size</th><th scope="col">Area</th><th scope="col">Type</th><th scope="col">Rate</th></tr>\n' +
    '            </thead>\n' +
    '            <tbody>\n' + rows + '\n' +
    '            </tbody>\n' +
    '          </table>\n' +
    '          ' + END;
}

function replaceBlock(file, block) {
  const p = path.join(ROOT, file);
  let text = fs.readFileSync(p, 'utf8');
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a < 0 || b < 0) throw new Error('markers not found in ' + file);
  text = text.slice(0, a) + block + text.slice(b + END.length);
  fs.writeFileSync(p, text);
  return p;
}

(async () => {
  const data = await get('movein');
  const units = ((data && data.unitTypes) || [])
    .filter((u) => u && u.width && u.length)
    .sort((a, b) => (Number(a.sqft) || 0) - (Number(b.sqft) || 0));

  if (!units.length) {
    console.error('The feed returned no unit types. Nothing written: an empty');
    console.error('table would be worse than a stale one.');
    process.exit(1);
  }

  const when = longDate(new Date());
  const block = table(units, when);

  ['pages/lubbock-2213-n-quaker.html', 'pages/size-guide.html'].forEach((f) => {
    replaceBlock(f, block);
    console.log('wrote ' + f);
  });

  console.log('\n' + units.length + ' sizes, confirmed ' + when + '.');
  console.log('Now: bash tools/build-preview.sh && node tools/check.js');
})().catch((e) => {
  console.error('failed:', e.message);
  process.exit(1);
});
